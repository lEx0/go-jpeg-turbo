//go:build amd64 && !purego

package dct

import "github.com/lEx0/go-jpeg-turbo/internal/cpuinfo"

// x86 kernels (dct_amd64.s, generated by asmgen_x86.go), chosen at run time
// by level (see level.go): SSE4.1, AVX2 and, for the forward DCT, AVX-512;
// the Go level runs the portable kernels of fast.go. The wrappers in
// dispatch.go check the arguments, so the kernels never access memory
// outside the slices and arrays they are given.
//
// The AVX512 level runs the AVX2 inverse DCT. The two passes of idctRows
// and idctCols have no pairs of values that go through the same sequence of
// operations, so 512-bit registers would only help the transposes, and on
// Zen 4 (EPYC 8124P), which executes them in 256-bit halves, they do not: a
// dependent 8x8 int32 transpose takes 14 cycles in ymm (VPUNPCK*,
// VPERM2I128), 12 in zmm (VPERMT2D) when the data stays in zmm and 20 when
// it comes from and goes back to ymm, while VPADDD and VPMULLD on zmm have
// half the throughput of ymm (0.5 and 1 cycle per instruction against 0.25
// and 0.5). The AVX-512 forward DCT gains in its tail: the quantized block
// fits in two zmm registers, VPERMI2W puts it in zig-zag order and
// VPTESTMW builds the bitmap (29 ns per block against 32.5 for AVX2 on that
// machine).

// dequantIDCTStoreSSE41 and dequantIDCTStoreAVX2 are DequantIDCTStoreRef
// for stride >= 8. They read b[:] and qt[:] (b is not written) and write
// only dst[y*stride+x] for x, y in [0, 8), as 8-byte rows.
//
//go:noescape
func dequantIDCTStoreSSE41(b, qt *Block, dst *byte, stride int)

//go:noescape
func dequantIDCTStoreAVX2(b, qt *Block, dst *byte, stride int)

// dequantIDCTSSE41 and dequantIDCTAVX2 are DequantIDCTRef. They read b[:]
// and qt[:] and write b[:].
//
//go:noescape
func dequantIDCTSSE41(b, qt *Block)

//go:noescape
func dequantIDCTAVX2(b, qt *Block)

// fdctQuantSSE41, fdctQuantAVX2 and fdctQuantAVX512 are FDCTQuantRef for a
// table accepted by init and stride >= 0. They read src[y*stride+x] for
// x, y in [0, 8) (as 4-byte (SSE4.1) or 8-byte rows) and t.xtab, and write
// out[:].
//
//go:noescape
func fdctQuantSSE41(src *byte, stride int, t *Quant, out *[BlockSize]int16) uint64

//go:noescape
func fdctQuantAVX2(src *byte, stride int, t *Quant, out *[BlockSize]int16) uint64

//go:noescape
func fdctQuantAVX512(src *byte, stride int, t *Quant, out *[BlockSize]int16) uint64

// quantSSE41, quantAVX2 and quantAVX512 are the quantization part of the
// fdctQuant kernels alone, for the tests: c holds the transformed block in
// column-major order (c[8*col+row]), each value in [-8192, 8191]. They read
// c[:] and t.xtab and write out[:].
//
//go:noescape
func quantSSE41(c *Block, t *Quant, out *[BlockSize]int16) uint64

//go:noescape
func quantAVX2(c *Block, t *Quant, out *[BlockSize]int16) uint64

//go:noescape
func quantAVX512(c *Block, t *Quant, out *[BlockSize]int16) uint64

func dequantIDCTStore(b, qt *Block, dst []byte, stride int) {
	switch {
	case level >= cpuinfo.AVX2:
		dequantIDCTStoreAVX2(b, qt, &dst[0], stride)
	case level == cpuinfo.SSE41:
		dequantIDCTStoreSSE41(b, qt, &dst[0], stride)
	default:
		dequantIDCTStoreGo(b, qt, dst, stride)
	}
}

func dequantIDCT(b, qt *Block) {
	switch {
	case level >= cpuinfo.AVX2:
		dequantIDCTAVX2(b, qt)
	case level == cpuinfo.SSE41:
		dequantIDCTSSE41(b, qt)
	default:
		dequantIDCTGo(b, qt)
	}
}

func fdctQuant(src []byte, stride int, t *Quant, out *[BlockSize]int16) uint64 {
	switch {
	case level >= cpuinfo.AVX512:
		return fdctQuantAVX512(&src[0], stride, t, out)
	case level == cpuinfo.AVX2:
		return fdctQuantAVX2(&src[0], stride, t, out)
	case level == cpuinfo.SSE41:
		return fdctQuantSSE41(&src[0], stride, t, out)
	}
	return fdctQuantGo(src, stride, t, out)
}

// initVec fills t.xtab for the x86 kernels: for layout l and word i of the
// quantized block as the kernels of the layout hold it in their registers
// (coefficient layoutCoef(l, i)), bias[i] = 4q, mul[i], scale[i] = 2^(16-s)
// and shift[i] = s with mul, s = magic16(8q), q the table entry of the
// coefficient.
// For x = |a| + 4q < 2^14: (x*mul) >> (16+s) = x / 8q, because e = mul*8q -
// 2^(16+s) is below 8q and 2^(16+s) > 2^15*8q (see magic16), so x*e <
// 2^(16+s); PMULHUW by mul and then by scale (SSE4.1, AVX2) or VPSRLVW by
// shift (AVX-512) computes it exactly.
func (t *Quant) initVec() {
	for l := range t.xtab {
		v := &t.xtab[l]
		for i := 0; i < BlockSize; i++ {
			q := uint32(t.Q[zigOf[layoutCoef(l, i)]])
			mul, s := magic16(8 * q)
			v[i] = int16(4 * q)
			v[BlockSize+i] = int16(uint16(mul))
			v[2*BlockSize+i] = int16(uint16(1) << (16 - s))
			v[3*BlockSize+i] = int16(s)
		}
	}
}

// layoutCoef returns the natural index of word i of the quantized block in
// layout l of the x86 kernels (asmgen_x86.go has the same function).
// Layout 0 (SSE4.1, AVX-512): 8-word block b = i/8 holds SSE register j =
// sseOrder[b], whose word w is (row 4*(j/4) + w%4, column 2*(j%4) + w/4).
// Layout 1 (AVX2): register a = i/16, lane ln = (i%16)/8, w = i%8: (row
// 4*ln + w%4, column a, or 7-a for w >= 4).
func layoutCoef(l, i int) int {
	if l == 0 {
		j, w := sseOrder[i/8], i%8
		return 8*(4*(j/4)+w%4) + 2*(j%4) + w/4
	}
	a, ln, w := i/16, (i%16)/8, i%8
	col := a
	if w >= 4 {
		col = 7 - a
	}
	return 8*(4*ln+w%4) + col
}

var sseOrder = [8]int{0, 4, 1, 5, 2, 6, 3, 7}
