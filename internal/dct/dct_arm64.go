//go:build arm64 && !purego

package dct

// NEON kernels (dct_arm64.s, generated by asmgen.go). The wrappers in
// dispatch.go check the arguments, so the kernels never access memory
// outside the slices and arrays they are given.

// dequantIDCTStoreNEON is DequantIDCTStoreRef for stride >= 8. It reads
// b[:] and qt[:] (b is not written) and writes only dst[y*stride+x] for x, y
// in [0, 8), as 8-byte rows.
//
//go:noescape
func dequantIDCTStoreNEON(b, qt *Block, dst *byte, stride int)

// dequantIDCTNEON is DequantIDCTRef. It reads b[:] and qt[:] and writes
// b[:].
//
//go:noescape
func dequantIDCTNEON(b, qt *Block)

// fdctQuantNEON is FDCTQuantRef for a table accepted by init and stride >=
// 0. It reads src[y*stride+x] for x, y in [0, 8) (as 8-byte rows) and
// t.vtab, and writes out[:].
//
//go:noescape
func fdctQuantNEON(src *byte, stride int, t *Quant, out *[BlockSize]int16) uint64

// quantNEON is the quantization part of fdctQuantNEON alone, for the tests:
// c holds the transformed block in column-major order (c[8*col+row]), each
// value in [-8192, 8191]. It reads c[:] and t.vtab and writes out[:].
//
//go:noescape
func quantNEON(c *[BlockSize]int16, t *Quant, out *[BlockSize]int16) uint64

func dequantIDCTStore(b, qt *Block, dst []byte, stride int) {
	dequantIDCTStoreNEON(b, qt, &dst[0], stride)
}

func dequantIDCT(b, qt *Block) {
	dequantIDCTNEON(b, qt)
}

func fdctQuant(src []byte, stride int, t *Quant, out *[BlockSize]int16) uint64 {
	return fdctQuantNEON(&src[0], stride, t, out)
}

// initVec fills t.vtab for fdctQuantNEON: for each column c of the
// transformed block, 3 vectors of 8 int16 lanes (lane r = row r): bias
// (4q), mul and -k, where q is the table entry of coefficient (r, c) and,
// with s = 15+k, mul = ceil(2^s / 8q) is the largest such value below 2^15.
// Then 2^s > 16383 * 8q (the next s would give mul >= 2^15), the error
// e = mul*8q - 2^s is below 8q, so for x < 2^14, x*e < 2^s and
// (x*mul) >> s = x / 8q.
func (t *Quant) initVec() {
	for col := 0; col < 8; col++ {
		v := t.vtab[24*col : 24*col+24 : 24*col+24]
		for row := 0; row < 8; row++ {
			q := uint32(t.Q[zigOf[8*row+col]])
			mul, k := magic15(8 * q)
			v[row] = int16(4 * q)
			v[8+row] = int16(mul)
			v[16+row] = -int16(k)
		}
	}
}
